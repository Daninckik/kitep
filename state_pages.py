def get_state_pages() -> dict:
    """Шаблоны с учётом правок из админ-панели (настройка «Госшаблоны»)."""
    import copy

    import db
    pages = copy.deepcopy(DEFAULT_STATE_PAGES)
    override = db.get_setting("state_pages", {}) or {}
    for key, patch in override.items():
        if key in pages and isinstance(patch, dict):
            pages[key].update({k: v for k, v in patch.items() if isinstance(v, str)})
    return pages
